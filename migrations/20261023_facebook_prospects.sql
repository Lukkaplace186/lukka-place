-- Facebook group prospects: phone numbers found in property posts, to invite as agents (2026-10-23).
--
-- Run with:  node scripts/run-sql-migration.js migrations/20261023_facebook_prospects.sql --write
--
-- IDEMPOTENT. A new table only. Written by web's POST /api/ingest/facebook-lead
-- (lib/facebookProspects.js), read by web's `npm run export:leads`.
--
-- Deliberately NOT the engine's `leads` table: a lead is a CUSTOMER request
-- (SQLite, NEW → … → CONVERTED, dispatched to ranked agencies). A number in a
-- Facebook group post is a broker we might recruit; filing it as a lead would
-- push it into lead dispatch, the agent inboxes and every conversion figure.
--
-- phone is the digits-only DRC form (243 + 9 digits), the form agents.phone is
-- compared in once its digits are folded. One row per number: a number seen in
-- a second post bumps seen_count / last_seen_at and keeps the first post.
-- Only pending_invite is written today; the other statuses are for whoever
-- runs the invitations.

BEGIN;

CREATE TABLE IF NOT EXISTS facebook_prospects (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone         TEXT NOT NULL UNIQUE CHECK (phone ~ '^243[0-9]{9}$'),
  author_name   TEXT,
  group_name    TEXT,
  post_url      TEXT,
  post_excerpt  TEXT,
  source        TEXT NOT NULL DEFAULT 'facebook_group' CHECK (source IN ('facebook_group')),
  status        TEXT NOT NULL DEFAULT 'pending_invite'
                CHECK (status IN ('pending_invite', 'invited', 'registered', 'declined')),
  seen_count    INTEGER NOT NULL DEFAULT 1,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  last_seen_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS facebook_prospects_status_created_idx
  ON facebook_prospects (status, created_at);

-- Closed to PostgREST, like every table since 20261015_rls_lockdown.sql.
ALTER TABLE facebook_prospects ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON facebook_prospects FROM anon, authenticated;
REVOKE ALL ON SEQUENCE facebook_prospects_id_seq FROM anon, authenticated;

COMMIT;
