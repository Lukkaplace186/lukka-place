-- Guides & Actualités: posts written from the console (/admin/blog) and shown
-- on /guides once the `publicBlog` switch is on (/admin/settings). The four
-- evergreen guides stay in web/lib/guides.js; a post with the same slug
-- replaces that guide's text. web/CLAUDE.md, "Guides & Actualités".
--
-- Run with:  node scripts/run-sql-migration.js migrations/20261026_blog_posts.sql --write
--
-- ADDITIVE AND IDEMPOTENT. A new table only. Before it runs, /guides shows the
-- code guides and /admin/blog says the table is missing.

BEGIN;

CREATE TABLE IF NOT EXISTS blog_posts (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug             TEXT NOT NULL CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND char_length(slug) <= 120),
  category         TEXT NOT NULL DEFAULT 'actualite' CHECK (category IN ('guide', 'actualite')),
  -- 'published' with published_at in the future is a scheduled post: public
  -- from that instant, no job needed.
  status           TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published')),
  published_at     TIMESTAMPTZ,
  title_fr         TEXT NOT NULL CHECK (char_length(title_fr) BETWEEN 1 AND 200),
  summary_fr       TEXT NOT NULL DEFAULT '' CHECK (char_length(summary_fr) <= 400),
  body_fr          TEXT NOT NULL DEFAULT '' CHECK (char_length(body_fr) <= 60000),
  title_en         TEXT CHECK (title_en IS NULL OR char_length(title_en) <= 200),
  summary_en       TEXT CHECK (summary_en IS NULL OR char_length(summary_en) <= 400),
  body_en          TEXT CHECK (body_en IS NULL OR char_length(body_en) <= 60000),
  cover_url        TEXT CHECK (cover_url IS NULL OR cover_url ~ '^https://'),
  cover_alt        TEXT CHECK (cover_alt IS NULL OR char_length(cover_alt) <= 200),
  -- What the post is about, for the "Biens en ligne" block and its link to
  -- the matching listings page. Each optional.
  purpose          TEXT CHECK (purpose IS NULL OR purpose IN ('location', 'vente')),
  commune          TEXT CHECK (commune IS NULL OR char_length(commune) <= 80),
  property_type    TEXT CHECK (property_type IS NULL OR char_length(property_type) <= 80),
  created_by       BIGINT,
  updated_by       BIGINT,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  deleted_at       TIMESTAMPTZ,
  CHECK (status = 'draft' OR published_at IS NOT NULL)
);

-- A deleted post frees its slug.
CREATE UNIQUE INDEX IF NOT EXISTS blog_posts_slug_live_idx ON blog_posts (slug) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS blog_posts_public_idx ON blog_posts (published_at DESC)
  WHERE status = 'published' AND deleted_at IS NULL;

ALTER TABLE blog_posts ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE
  role_name TEXT;
BEGIN
  FOREACH role_name IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = role_name) THEN
      EXECUTE format('REVOKE ALL ON blog_posts FROM %I', role_name);
      EXECUTE format('REVOKE ALL ON SEQUENCE blog_posts_id_seq FROM %I', role_name);
    END IF;
  END LOOP;
END $$;

COMMIT;
