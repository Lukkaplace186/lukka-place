-- Asking prices seen OUTSIDE Lukka Place's own public listings.
--
-- Run with:  node scripts/run-sql-migration.js migrations/20261104_market_observations.sql --write
--
-- ADDITIVE AND IDEMPOTENT. Written by the engine's services/marketObservations.js
-- (WhatsApp group captures and the website collectors, scheduler job
-- `market-observations`) and by web's /admin/market-data (a post a team
-- member read on Facebook or Zwandako and entered by hand). Read by web's
-- price guide (/combien-coute) and the admin commune comparison.
--
-- One row = one advert seen once, at one source. FACTS ONLY: price, period,
-- bedrooms, commune, furnished, the source's own id and link. No photo, no
-- description, no phone number is stored — nothing here is ever shown as a
-- listing. `title` is kept for the admin review list only (≤ 200 chars).
--
-- `source_ref` is the source's own identifier (a WordPress post id, an
-- IMCongo reference, a SmartImmo uuid, an engine SQLite listing id, a pasted
-- link); (source, source_ref) is unique, so re-collecting refreshes
-- `last_seen_at` instead of adding a row.
--
-- `property_id` is the Lukka `properties.id` a WhatsApp group capture was
-- published as: while that property is public it is already counted as a
-- Lukka listing, and readers skip the observation (never counted twice).
--
-- `excluded_reason` NULL = counts. Set by the collector (price out of range,
-- francs, short stay…) or by a team member from the admin list.

BEGIN;

CREATE TABLE IF NOT EXISTS market_observations (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source         text        NOT NULL,
  source_ref     text        NOT NULL,
  source_url     text,
  property_id    bigint,
  posted_at      timestamptz,
  first_seen_at  timestamptz NOT NULL DEFAULT NOW(),
  last_seen_at   timestamptz NOT NULL DEFAULT NOW(),
  purpose        text        NOT NULL,
  property_kind  text,
  beds           smallint,
  furnished      boolean,
  price          numeric,
  currency       text,
  price_period   text,
  monthly_usd    numeric,
  price_usd      numeric,
  city           text,
  commune        text,
  quartier       text,
  title          text,
  excluded_reason text,
  recorded_by    bigint,
  created_at     timestamptz NOT NULL DEFAULT NOW(),
  updated_at     timestamptz NOT NULL DEFAULT NOW(),
  CONSTRAINT market_observations_source_check CHECK (source IN (
    'whatsapp_group', 'immo24', 'imcongo', 'alain_realty', 'smartimmo',
    'facebook', 'zwandako', 'other'
  )),
  CONSTRAINT market_observations_purpose_check CHECK (purpose IN ('rent', 'sale')),
  CONSTRAINT market_observations_beds_check CHECK (beds IS NULL OR beds BETWEEN 0 AND 30),
  CONSTRAINT market_observations_title_len CHECK (title IS NULL OR length(title) <= 200),
  CONSTRAINT market_observations_source_ref_key UNIQUE (source, source_ref)
);

CREATE INDEX IF NOT EXISTS market_observations_guide_idx
  ON market_observations (purpose, commune, beds)
  WHERE excluded_reason IS NULL;

CREATE INDEX IF NOT EXISTS market_observations_seen_idx
  ON market_observations (last_seen_at DESC);

-- One row per source: when it was last collected and what came back, for the
-- admin page ("Immo24 — collecté le 4 nov., 25 annonces") and so a failing
-- collector is visible rather than silently stale.
CREATE TABLE IF NOT EXISTS market_source_runs (
  source        text PRIMARY KEY,
  last_run_at   timestamptz,
  last_ok_at    timestamptz,
  fetched       integer,
  stored        integer,
  excluded      integer,
  last_error    text
);

ALTER TABLE market_observations ENABLE ROW LEVEL SECURITY;
ALTER TABLE market_source_runs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON market_observations FROM anon, authenticated;
REVOKE ALL ON market_source_runs FROM anon, authenticated;
REVOKE ALL ON SEQUENCE market_observations_id_seq FROM anon, authenticated;

COMMIT;
