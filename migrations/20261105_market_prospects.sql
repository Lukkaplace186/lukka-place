-- Agents to recruit, found in the adverts the team pastes for the price guide.
--
-- Run with:  node scripts/run-sql-migration.js migrations/20261105_market_prospects.sql --write
--
-- ADDITIVE AND IDEMPOTENT. Written and read only by web's console
-- (/admin/market-data/marche "Coller des annonces" and
-- /admin/market-data/prospects). One paste fills both: each advert's price
-- facts go to market_observations (which still holds no phone number), and
-- the person who posted it goes here, one row per phone number.
--
-- `phone` is digits only (243… for a DRC number), the key a second paste of
-- the same agent lands on: it adds the source and counts the advert, and
-- never overwrites a name, agency or note a team member already has.
-- `status` is the team's follow-up, the vocabulary of the earlier tracker:
-- todo / noanswer / callback / interested / signed / declined / optout.

BEGIN;

CREATE TABLE IF NOT EXISTS market_prospects (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone           text        NOT NULL,
  name            text,
  agency          text,
  sources         text[]      NOT NULL DEFAULT '{}',
  first_url       text,
  adverts_count   integer     NOT NULL DEFAULT 0,
  last_advert_at  timestamptz,
  status          text        NOT NULL DEFAULT 'todo',
  contacted_on    date,
  channel         text,
  notes           text,
  created_by      bigint,
  updated_by      bigint,
  created_at      timestamptz NOT NULL DEFAULT NOW(),
  updated_at      timestamptz NOT NULL DEFAULT NOW(),
  CONSTRAINT market_prospects_phone_key UNIQUE (phone),
  CONSTRAINT market_prospects_phone_check CHECK (phone ~ '^[0-9]{7,15}$'),
  CONSTRAINT market_prospects_status_check CHECK (status IN (
    'todo', 'noanswer', 'callback', 'interested', 'signed', 'declined', 'optout'
  )),
  CONSTRAINT market_prospects_channel_check CHECK (channel IS NULL OR channel IN (
    'whatsapp', 'phone', 'in_person', 'facebook', 'other'
  )),
  CONSTRAINT market_prospects_name_len CHECK (name IS NULL OR length(name) <= 120),
  CONSTRAINT market_prospects_agency_len CHECK (agency IS NULL OR length(agency) <= 120),
  CONSTRAINT market_prospects_notes_len CHECK (notes IS NULL OR length(notes) <= 2000)
);

-- Which saved observations a prospect posted (the adverts behind the count).
CREATE TABLE IF NOT EXISTS market_prospect_adverts (
  prospect_id     bigint NOT NULL REFERENCES market_prospects(id) ON DELETE CASCADE,
  observation_id  bigint NOT NULL REFERENCES market_observations(id) ON DELETE CASCADE,
  PRIMARY KEY (prospect_id, observation_id)
);

CREATE INDEX IF NOT EXISTS market_prospects_status_idx ON market_prospects (status, last_advert_at DESC);
CREATE INDEX IF NOT EXISTS market_prospect_adverts_obs_idx ON market_prospect_adverts (observation_id);

ALTER TABLE market_prospects ENABLE ROW LEVEL SECURITY;
ALTER TABLE market_prospect_adverts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON market_prospects FROM anon, authenticated;
REVOKE ALL ON market_prospect_adverts FROM anon, authenticated;
REVOKE ALL ON SEQUENCE market_prospects_id_seq FROM anon, authenticated;

COMMIT;
