-- Where Lukka Place itself posted a listing on social media.
--
-- Run with:  node scripts/run-sql-migration.js migrations/20261106_team_social_posts.sql --write
--
-- ADDITIVE AND IDEMPOTENT. Written and read only by web's console
-- (/admin/listings, the "Carte réseaux sociaux" dialog, audience "team").
-- One row each time a team member marks a listing as posted in one place: a
-- Facebook group, the company's own Facebook page, its Instagram.
--
-- Why it exists (2026-11-06): the team posts listings into ~25 Kinshasa
-- property groups by hand, and nothing recorded which listing went where.
-- The same Gombe listing was about to be posted twice in one group whose
-- admins approve every post. listing_shares is not the place: it records what
-- AGENTS did with their own listings (web/CLAUDE.md, "Statut du jour").
--
-- What a row says is that a team member SAID they posted it, not that the
-- post was published: a group's admins may still decline it.
--
-- `target_key` is the place's slug (web lib/teamSocialTargets.js) and also the
-- `utm_campaign` of the link in that post's caption, so visits can be traced
-- back to the group. No foreign key to properties, the same choice as
-- sales_listing_credits: agents hard-delete listings.

BEGIN;

CREATE TABLE IF NOT EXISTS team_social_posts (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  property_id     integer     NOT NULL,
  target_key      text        NOT NULL,
  target_label    text        NOT NULL,
  posted_at       timestamptz NOT NULL DEFAULT NOW(),
  posted_by       bigint,
  posted_by_label text,
  CONSTRAINT team_social_posts_target_key_check CHECK (target_key ~ '^[a-z0-9][a-z0-9-]{0,59}$'),
  CONSTRAINT team_social_posts_target_label_check CHECK (char_length(btrim(target_label)) BETWEEN 1 AND 120)
);

CREATE INDEX IF NOT EXISTS team_social_posts_property_idx ON team_social_posts (property_id, posted_at DESC);
CREATE INDEX IF NOT EXISTS team_social_posts_target_idx ON team_social_posts (target_key, posted_at DESC);

-- Closed to PostgREST like every console table (CLAUDE.md, "New tables start closed").
REVOKE ALL ON team_social_posts FROM anon, authenticated;

COMMIT;
