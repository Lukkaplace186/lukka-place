-- "Mon déménagement": up to five projects per customer (owner, 2026-11-07).
--
-- Run with:  node scripts/run-sql-migration.js migrations/20261107_move_projects_multiple.sql --write
--
-- ADDITIVE AND IDEMPOTENT. The table was one row per customer (PRIMARY KEY
-- customer_id). Now each project has its own id, an optional title, and the
-- key moves to that id; existing rows keep their data and get an id. The
-- five-per-customer ceiling is enforced by web's lib/moveProjects.js (a COUNT
-- guard in the INSERT, like favourites and saved searches), not here.
--
-- Until this runs, web keeps working with one project per customer
-- (lib/moveProjects.js falls back on 42703).

BEGIN;

ALTER TABLE customer_move_projects ADD COLUMN IF NOT EXISTS id bigint GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE customer_move_projects ADD COLUMN IF NOT EXISTS title text;

DO $$
BEGIN
  -- Move the primary key from customer_id to id, once.
  IF EXISTS (
    SELECT 1 FROM pg_constraint c
     WHERE c.conrelid = 'customer_move_projects'::regclass
       AND c.contype = 'p'
       AND pg_get_constraintdef(c.oid) = 'PRIMARY KEY (customer_id)'
  ) THEN
    ALTER TABLE customer_move_projects DROP CONSTRAINT customer_move_projects_pkey;
    ALTER TABLE customer_move_projects ADD CONSTRAINT customer_move_projects_pkey PRIMARY KEY (id);
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS customer_move_projects_customer_idx
  ON customer_move_projects (customer_id, created_at);

COMMIT;
