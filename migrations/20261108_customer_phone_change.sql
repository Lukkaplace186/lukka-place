-- "Changer de numéro": a signed-in customer moves their account to a new
-- WhatsApp number by typing a code sent to that NEW number.
--
-- Run with:  node scripts/run-sql-migration.js migrations/20261108_customer_phone_change.sql --write
--
-- ADDITIVE AND IDEMPOTENT. Written by web's lib/customerPhoneChange.js
-- (/compte/client/parametres/numero).
--
-- customers.phone_change_*: the one change in flight. The pending number, the
--   code's hash and expiry, how many wrong codes were typed, and a send
--   counter per hour (a code is a WhatsApp message to a number nobody has
--   proved yet, so sends are capped). Separate from otp_code_hash (signup)
--   and reset_otp_code_hash (password reset): one flow never cancels
--   another's code.
--
-- customer_phone_history: every number the account left. Requests and visits
--   live in the engine keyed by wa_id, so the account keeps showing those
--   made under an old number. Never a login identity: signing in is by
--   customers.phone only.

BEGIN;

ALTER TABLE customers ADD COLUMN IF NOT EXISTS phone_change_to         text;
ALTER TABLE customers ADD COLUMN IF NOT EXISTS phone_change_code_hash  text;
ALTER TABLE customers ADD COLUMN IF NOT EXISTS phone_change_expires_at timestamptz;
ALTER TABLE customers ADD COLUMN IF NOT EXISTS phone_change_attempts   integer NOT NULL DEFAULT 0;
ALTER TABLE customers ADD COLUMN IF NOT EXISTS phone_change_sends      integer NOT NULL DEFAULT 0;
ALTER TABLE customers ADD COLUMN IF NOT EXISTS phone_change_window_at  timestamptz;

CREATE TABLE IF NOT EXISTS customer_phone_history (
  id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id bigint      NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
  phone       text        NOT NULL,
  changed_at  timestamptz NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS customer_phone_history_customer_idx
  ON customer_phone_history (customer_id, changed_at DESC);

ALTER TABLE customer_phone_history ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON customer_phone_history FROM anon, authenticated;

COMMIT;
