-- "Faites le point sur vos annonces" — one request per agent, not one
-- question per listing (2026-11-09, owner decision).
--
-- The per-listing "Toujours disponible ?" (20260929) asked about each listing
-- every 14 days, three a day per agent: the agent with 49 listings would have
-- been asked every single day, and the one "loué" answer it got never gave a
-- price (multi-step chats lose people at every step). Now the engine sends ONE
-- WhatsApp per agent every 14 days carrying a private link; the agent answers
-- for every listing on one page (web /point/<token>), or taps "Rien n'a
-- changé" in WhatsApp.
--
--  * agent_status_requests: one row per request sent. Only the SHA-256 of the
--    link's token is stored. The link is good for LINK_TTL_DAYS (7) and can
--    only change the status of that agent's own listings.
--  * listing_availability_checks gains channel 'LINK', the answers the page
--    can give about an under-offer or paused listing, and request_id.
--  * properties.auto_paused_at for the (dormant) auto-pause.
--
-- Idempotent. Code runs before it: the engine job refuses to start without
-- agent_status_requests (to_regclass), and answers recorded before the CHECKs
-- are widened fail softly (the listing itself is still updated).

BEGIN;

CREATE TABLE IF NOT EXISTS agent_status_requests (
  id                bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agent_id          bigint      NOT NULL REFERENCES agents (id) ON DELETE CASCADE,
  token_hash        text        NOT NULL UNIQUE,
  created_at        timestamptz NOT NULL DEFAULT NOW(),
  expires_at        timestamptz NOT NULL,
  delivery          text        CHECK (delivery IS NULL OR delivery IN ('template', 'session-link')),
  listings_count    integer     CHECK (listings_count IS NULL OR listings_count >= 0),
  opened_at         timestamptz,
  last_answer_at    timestamptz,
  answers_count     integer     NOT NULL DEFAULT 0,
  all_confirmed_at  timestamptz
);

CREATE INDEX IF NOT EXISTS agent_status_requests_agent_idx
  ON agent_status_requests (agent_id, created_at DESC);

ALTER TABLE agent_status_requests ENABLE ROW LEVEL SECURITY;

-- Auto-pause (services/listingAutoPause.js, OFF until LISTING_AUTO_PAUSE=on):
-- a listing unconfirmed for 30 days whose agent was asked and did not answer
-- is hidden (status 0) with this stamp, which tells it apart from an agent's
-- own "Archiver" and lets "Faites le point" offer "Réactiver".
ALTER TABLE properties ADD COLUMN IF NOT EXISTS auto_paused_at timestamptz;

ALTER TABLE listing_availability_checks
  ADD COLUMN IF NOT EXISTS request_id bigint REFERENCES agent_status_requests (id) ON DELETE SET NULL;

ALTER TABLE listing_availability_checks DROP CONSTRAINT IF EXISTS listing_availability_checks_channel_check;
ALTER TABLE listing_availability_checks ADD CONSTRAINT listing_availability_checks_channel_check
  CHECK (channel IN ('WHATSAPP', 'DASHBOARD', 'LINK'));

ALTER TABLE listing_availability_checks DROP CONSTRAINT IF EXISTS listing_availability_checks_answer_check;
ALTER TABLE listing_availability_checks ADD CONSTRAINT listing_availability_checks_answer_check
  CHECK (answer IS NULL OR answer IN (
    'AVAILABLE', 'PRICE_CHANGED', 'LET_OR_SOLD', 'WITHDRAWN',
    'UNDER_OFFER', 'STILL_UNDER_OFFER', 'BACK_ON_MARKET', 'REACTIVATED'
  ));

DO $$
DECLARE
  role_name TEXT;
BEGIN
  FOREACH role_name IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = role_name) THEN
      EXECUTE format('REVOKE ALL ON agent_status_requests FROM %I', role_name);
      EXECUTE format('REVOKE ALL ON SEQUENCE agent_status_requests_id_seq FROM %I', role_name);
    END IF;
  END LOOP;
END $$;

COMMIT;
