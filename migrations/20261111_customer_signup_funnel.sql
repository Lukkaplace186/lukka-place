-- Customer sign-up funnel (2026-11-11, owner goal: 1,000 customer accounts).
--
-- One row per step a visitor takes towards a customer account: a prompt shown
-- (the ♥ modal, the nudge card), its button pressed, the sign-up page loaded,
-- the form touched, sent, refused (with the reason) or the account created
-- (with its id). `entry` names where it started (web lib/signupFunnelRules.js
-- SIGNUP_ENTRIES), so /admin/croissance can say which prompt produces
-- accounts and where people give up. Where the visitor came from stays in
-- account_acquisitions / visitor_touches; `source` here is the beacon's own
-- campaign tag, for prompts that never became an account.
--
-- Written by web only (POST /api/telemetry/signup-funnel for browser steps,
-- signupAction for refused / created). Code runs before this migration: a
-- missing table (42P01) records nothing and the dashboard shows nothing.
--
-- Idempotent. New tables start closed to anon/authenticated (default
-- privileges, 20261015_rls_lockdown.sql); the REVOKE is kept anyway.

BEGIN;

CREATE TABLE IF NOT EXISTS customer_signup_events (
  id           bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at   timestamptz NOT NULL DEFAULT NOW(),
  visitor_id   text        CHECK (visitor_id IS NULL OR char_length(visitor_id) <= 64),
  entry        text        NOT NULL CHECK (char_length(entry) BETWEEN 1 AND 32),
  step         text        NOT NULL CHECK (step IN (
                 'prompt_shown', 'prompt_open', 'form_view', 'form_start', 'submit', 'refused', 'created')),
  source       text        CHECK (source IS NULL OR char_length(source) <= 64),
  device       text        CHECK (device IS NULL OR char_length(device) <= 32),
  viewer_kind  text        CHECK (viewer_kind IS NULL OR char_length(viewer_kind) <= 16),
  refusal      text        CHECK (refusal IS NULL OR refusal IN ('name', 'phone', 'password', 'exists', 'ref')),
  customer_id  bigint
);

CREATE INDEX IF NOT EXISTS customer_signup_events_created_idx
  ON customer_signup_events (created_at);
CREATE INDEX IF NOT EXISTS customer_signup_events_entry_step_idx
  ON customer_signup_events (entry, step, created_at);

ALTER TABLE customer_signup_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON customer_signup_events FROM anon, authenticated;

COMMIT;
