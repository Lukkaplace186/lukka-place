/**
 * Builds lib/data/cities.json from the engine's location data and the
 * geocoded centroids (engine scripts/geocode-communes.js, run on the VPS).
 *
 *   node web/scripts/build-cities-data.mjs <centroids.json>
 *
 * Run from the engine repo root. Kinshasa's own centroids stay in
 * lib/geocoding.js (KINSHASA_COMMUNE_CENTROIDS); this file lists its commune
 * keys only. tests/unit/cities-data.test.js fails if the commune lists here
 * and the engine's ever disagree.
 */
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const centroidsPath = process.argv[2];
if (!centroidsPath) {
  console.error('Usage: node web/scripts/build-cities-data.mjs <centroids.json>');
  process.exit(2);
}

const kinshasa = JSON.parse(fs.readFileSync(path.join(root, 'kinshasa_locations.json'), 'utf8'));
const drc = JSON.parse(fs.readFileSync(path.join(root, 'drc_locations.json'), 'utf8'));
const centroids = JSON.parse(fs.readFileSync(centroidsPath, 'utf8'));
const KEY_ALIASES = { "N'Djili": 'Ndjili', "N'Sele": 'Nsele' };
const label = (key) => key.replace(/\s*\([^)]*\)\s*$/, '');
const slug = (text) => text.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
const round = (n) => Math.round(n * 1e6) / 1e6;

const cities = [{
  name: 'Kinshasa',
  slug: 'kinshasa',
  province: 'Kinshasa',
  utcOffset: 1,
  center: null,
  communes: Object.keys(kinshasa).map((k) => ({ key: KEY_ALIASES[k] || k, label: KEY_ALIASES[k] || k, point: null })),
}];

for (const [name, city] of Object.entries(drc.cities)) {
  const geo = centroids[name] || { center: null, communes: {} };
  cities.push({
    name,
    slug: slug(name),
    province: city.province,
    utcOffset: city.utc_offset,
    center: geo.center ? { lat: round(geo.center.lat), lng: round(geo.center.lng) } : null,
    communes: Object.keys(city.communes).map((key) => {
      const p = geo.communes?.[key];
      return { key, label: label(key), point: p ? { lat: round(p.lat), lng: round(p.lng) } : null };
    }),
  });
}

const out = {
  _about: 'Generated by web/scripts/build-cities-data.mjs from the engine\'s kinshasa_locations.json + drc_locations.json and Google-geocoded centroids (engine scripts/geocode-communes.js, 2026-10-20). A null point means Google gave no commune-level answer inside that city: its listings are placed at the city centre, flagged approximate. Do not edit by hand.',
  cities,
};
const target = path.join(root, 'web', 'lib', 'data', 'cities.json');
fs.writeFileSync(target, `${JSON.stringify(out, null, 2)}\n`);
console.log(`wrote ${target}: ${cities.length} cities, ${cities.reduce((n, c) => n + c.communes.length, 0)} communes`);
