test('a share record is an allow-listed channel × format, with 1..5 distinct positive ids', () => {
  assert.deepEqual(normaliseShareRecord({ listingIds: [305, '305', 12], channel: 'status_share', format: 'story' }), {
    ids: [305, 12],
    channel: 'status_share',
    format: 'story',
  });
  assert.deepEqual(normaliseShareRecord({ listingId: 7, channel: 'print', format: 'fiche' }).ids, [7]);
  assert.equal(normaliseShareRecord({ listingIds: [1], channel: 'status_share', format: 'square' }), null, 'a Status is 9:16 only');
  assert.equal(normaliseShareRecord({ listingIds: [1], channel: 'print', format: 'text' }), null);
  assert.equal(normaliseShareRecord({ listingIds: [1], channel: 'report', format: 'square' }), null, 'the landlord report is not a share');
  assert.equal(normaliseShareRecord({ listingIds: [0, -3, 'x'], channel: 'kit_copy', format: 'text' }), null);
  const tooMany = Array.from({ length: MAX_IDS_PER_RECORD + 1 }, (_, i) => i + 1);
  assert.equal(normaliseShareRecord({ listingIds: tooMany, channel: 'status_download', format: 'story' }), null);
});

test('the migration CHECK constraints list exactly the channels and formats the code accepts', () => {
  const sql = readFileSync(path.join(ROOT, '..', 'migrations', '20260922_listing_shares.sql'), 'utf8');
  const listIn = (column) => {
    const m = sql.match(new RegExp(`${column}\\s+IN \\(([^)]*)\\)`));
    return m[1].match(/'([a-z_]+)'/g).map((s) => s.slice(1, -1)).sort();
  };
  assert.deepEqual(listIn('channel'), [...SHARE_CHANNELS].sort());
  assert.deepEqual(listIn('format'), [...SHARE_FORMATS].sort());
  assert.match(sql, /id\s+bigint\s+GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/);
  assert.match(sql, /CREATE TABLE IF NOT EXISTS listing_shares/);
  assert.match(sql, /REFERENCES properties \(id\) ON DELETE CASCADE/);
  assert.match(sql, /REFERENCES agents \(id\) ON DELETE CASCADE/);
  assert.equal(Object.keys(CHANNEL_FORMATS).length, SHARE_CHANNELS.length);
});

