test('recording checks ownership and the public filter in the INSERT, and dedupes one tap', async () => {
  await recordListingShares(9, { ids: [305, 306], channel: 'kit_share', format: 'story' });
  const { sql, values } = calls[0];
  assert.match(sql, /^INSERT INTO listing_shares \(property_id, agent_id, channel, format\) SELECT p\.id, \$2, \$3, \$4 FROM properties p/);
  assert.match(sql, /p\.agent_id = \$2/);
  assert.match(sql, /p\.status = 1 AND p\.approve_status = 1/);
  assert.match(sql, /NOT EXISTS \( SELECT 1 FROM listing_shares s WHERE s\.property_id = p\.id AND s\.agent_id = \$2 AND s\.channel = \$3 AND s\.format IS NOT DISTINCT FROM \$4 AND s\.created_at > NOW\(\) - make_interval\(secs => \$5\)/);
  assert.match(sql, /f\.agent_id = \$2 AND f\.created_at > NOW\(\) - interval '1 minute' \) < \$6/);
  assert.deepEqual(values.slice(0, 5), [[305, 306], 9, 'kit_share', 'story', 30]);
});

