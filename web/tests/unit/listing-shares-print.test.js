test('entry costs stay three separate lines, never summed, and unstated ones are left out', () => {
  const lines = entryCostLines({ purpose: 'rent', price: 500, price_period: 'mois', deposit_months: 3, advance_months: 1, commission_months: 1 });
  assert.deepEqual(lines.map((l) => [l.key, l.value, l.amount]), [
    ['deposit', '3 mois', `${(1500).toLocaleString('fr-FR')} $`],
    ['advance', '1 mois', '500 $'],
    ['commission', '1 mois', '500 $'],
  ]);
  assert.ok(!lines.some((l) => /5 mois/.test(l.value)), 'no "Garantie : 5 mois"');
  const depositOnly = entryCostLines({ purpose: 'rent', price: 500, price_period: 'an', deposit_months: 3, advance_months: null, commission_months: '' });
  assert.deepEqual(depositOnly.map((l) => [l.key, l.amount]), [['deposit', null]], 'a yearly rent gets no per-month amount');
  assert.deepEqual(entryCostLines({ purpose: 'sale', deposit_months: null }), []);
});

