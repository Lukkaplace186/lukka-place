test('suggestions: own live listings not shared recently, never-shared first, then newest', async () => {
  enqueue([{ id: '305', title: 'Appartement', price: '1000', last_shared_at: null, created_at: new Date() }]);
  const { items, tracked } = await getStatusSuggestions(9);
  assert.equal(tracked, true);
  assert.equal(items.length, 1);
  const { sql, values } = calls[0];
  assert.match(sql, /p\.agent_id = \$1 AND p\.status = 1 AND p\.approve_status = 1 AND COALESCE\(p\.listing_status, 'active'\) NOT IN \('under_offer', 'closed'\)/);
  assert.match(sql, /ls\.last_shared_at IS NULL OR ls\.last_shared_at < NOW\(\) - make_interval\(days => \$2\)/);
  assert.match(sql, /ORDER BY ls\.last_shared_at ASC NULLS FIRST, p\.created_at DESC, p\.id DESC LIMIT \$3/);
  assert.deepEqual(values, [9, 3, 5]);
  assert.deepEqual(serialiseSuggestion(items[0]).id, 305);
});

test('suggestions before the migration fall back to the newest live listings, flagged untracked', async () => {
  let n = 0;
  pool.query = async (text, values) => {
    const sql = String(text).replace(/\s+/g, ' ').trim();
    calls.push({ text, values, sql });
    n += 1;
    if (n === 1) {
      const err = new Error('relation "listing_shares" does not exist');
      err.code = '42P01';
      throw err;
    }
    return { rows: [{ id: 1 }], rowCount: 1 };
  };
  const { items, tracked } = await getStatusSuggestions(9);
  assert.equal(tracked, false);
  assert.equal(items.length, 1);
  assert.doesNotMatch(calls[1].sql, /listing_shares/);
  assert.match(calls[1].sql, /p\.status = 1 AND p\.approve_status = 1/);
});

