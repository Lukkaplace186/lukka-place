// Landlord report: "partagée N fois"
// ---------------------------------------------------------------------------

const NOW = new Date('2026-09-16T11:42:00Z');
const ROW = {
  id: 305, price: 1000, purpose: 'rent', price_period: 'mois', beds: 2, bath: 2, area: null, units_count: null,
  quartier: '24 Novembre', commune: 'Lingwala', status: 1, approve_status: 1, listing_status: null,
};
const COUNTS = {
  current: { views: 42, whatsappClicks: 5, saves: 2, visitRequests: 1 },
  previous: { views: 30, whatsappClicks: 2, saves: 0, visitRequests: 0 },
};
const opts = (shares) => ({ typeText: 'Appartement', brand: { name: 'Makam B', phone: null }, window: reportWindow(NOW), shares });
const measure = (text, { size, weight = 500 }) => String(text).length * size * (weight >= 700 ? 0.6 : 0.52);

test('"partagée N fois" appears only above zero, with what a share is', () => {
  assert.equal(shareCountText(0), null);
  assert.equal(shareCountText(null), null);
  assert.equal(shareCountText(3), 'Partagée 3 fois');

  const report = buildMandateReport(ROW, COUNTS, opts(3));
  assert.equal(report.shareText, 'Partagée 3 fois');
  const caption = buildMandateCaption(ROW, report, COUNTS);
  assert.match(caption, /📣 Partagée 3 fois par l’agent depuis Lukka Place/);
  assert.ok(caption.includes(SHARE_COUNT_DEFINITION));
  assert.match(SHARE_COUNT_DEFINITION, /pas une preuve que quelqu’un l’a vu/);

  for (const shares of [0, null, undefined]) {
    const quiet = buildMandateReport(ROW, COUNTS, opts(shares));
    assert.equal(quiet.shareText, null);
    const text = buildMandateCaption(ROW, quiet, COUNTS);
    assert.doesNotMatch(text, /Partagée/);
    assert.ok(!text.includes(SHARE_COUNT_DEFINITION));
  }
});

test('the report card draws the share line on the status row, inside the canvas', () => {
  const report = buildMandateReport(ROW, COUNTS, opts(12));
  const { width, height, ops } = buildReportOps(report, { measure, hasPhoto: true, hasMark: true });
  const line = ops.find((op) => op.type === 'text' && op.text === 'Partagée 12 fois');
  const status = ops.find((op) => op.type === 'text' && op.text === report.statusText);
  assert.ok(line, 'share line drawn');
  assert.equal(line.y, status.y);
  assert.equal(line.align, 'right');
  assert.ok(line.x - measure(line.text, line) >= 0 && line.x <= width && line.y <= height);
  const none = buildReportOps(buildMandateReport(ROW, COUNTS, opts(0)), { measure, hasPhoto: true, hasMark: true });
  assert.ok(!none.ops.some((op) => op.type === 'text' && /Partagée/.test(op.text)));
});

